"""outputs/FIGURES.md: every figure of figure_plan.py with its file, data sources, caption and the run-specific note of
its audit record (auto-generated after the figures; MODEL v3.0.0)."""
import json
import os

import figure_plan as FP
import layout
import runprofile


def _audit(fid):
    p = os.path.join(layout.FIGURE_AUDIT, f'{fid}.json')
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def _rel(path):
    return os.path.relpath(path, layout.OUT).replace(os.sep, '/')


def _entry(fid, title, caption, source, path):
    a = _audit(fid)
    files = [f'{_rel(path)}.{ext}' for ext in runprofile.get('formats') if os.path.exists(f'{path}.{ext}')]
    L = [f'### {fid}', '', f'**{title}**' + (f' — {caption}' if caption else ''), '',
         f"- Files: {', '.join(f'`{f}`' for f in files) if files else '(not drawn in this profile)'}",
         f"- Data: {', '.join(f'`data/{s}`' for s in source)}"]
    if a and a.get('note'):
        L.append(f"- This run: {a['note']}")
    return L + ['']


def write():
    full = runprofile.name() == 'full'
    L = ['# Figures (generated by figures/index.py; do not edit)', '',
         f"Run profile: **{runprofile.name()}** ({runprofile.get('n_draws'):,} Monte Carlo draws; formats "
         f"{', '.join(runprofile.get('formats'))} at {runprofile.get('dpi')} dpi). Every figure is drawn by the "
         'figures/ package from the data files listed (compute / draw separation).', '',
         '## Main paper (paper_main/)', '']
    for h in FP.PAPER_MAIN:
        L += _entry(h['file'], f"{h['id']} {h['title']}", h['caption'], h['source'], os.path.join(layout.PAPER_MAIN, h['file']))
    L += ['## Extended Data (paper_extended/)', '']
    for h in FP.PAPER_EXTENDED:
        L += _entry(h['file'], f"{h['id']} {h['title']}", None, h['source'], os.path.join(layout.PAPER_EXTENDED, h['file']))
    for t in FP.EXTENDED_TABLES:
        L += [f"### {t['file']}", '', f"**{t['id']} {t['title']}** (table)", '',
              f"- Files: `paper_extended/{t['file']}.md`, `paper_extended/{t['file']}.csv`",
              f"- Data: {', '.join(f'`data/{s}`' for s in t['source'])}", '']
    L += ['## Supplementary figures (supplementary/)', '']
    for h in FP.SUPPLEMENTARY:
        L += _entry(h['file'], f"{h['id']} {h['title']}", None, h['source'], os.path.join(layout.SUPPLEMENTARY, h['file']))
    for g, rows in FP.DIAGNOSTICS.items():
        L += [f'## Diagnostics: {g} (diagnostics/{g}/)', '']
        for r in rows:
            if r['file'] in FP.FULL_ONLY and not full:
                L += [f"### {r['file']}", '', f"**{r['title']}** — full profile only.", '']
                continue
            L += _entry(r['file'], r['title'], None, r['source'], os.path.join(layout.DIAGNOSTICS, g, r['file']))
    L += ['## Retired figures', ''] + [f'- {k}: {v}' for k, v in FP.RETIRED.items()] + ['']
    with open(layout.writing(layout.FIGURES_INDEX), 'w') as f:
        f.write('\n'.join(L))
