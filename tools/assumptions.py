"""Generate outputs/reports/ASSUMPTIONS.md: the assumption register and every setting of the
baseline projection (projection.py), the planetary-boundary layer (AESA; boundaries.py) and the
pathways and the theoretical limit TL (levers.py). No value is typed by hand: the register rows
(setting, value, basis) come from tools/baseline_draft.register(), boundaries.assumption_register(),
levers.register() and levers.register_tl() (with the resolved values of
outputs/data/pathways/levers.json and theoretical_limit.json), and each "All settings" table lists
every upper-case setting of its module as it is at run time.

    python tools/assumptions.py                   the whole document
    python tools/assumptions.py --pathways-only   only its Pathways section (as
                                                  tools/pathways_methods.py --sections)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import layout  # noqa: E402

OUT_MD = layout.report('ASSUMPTIONS.md', frozen=False)


# display and run-time switches: not model settings, and their value depends on how
# the tool is launched (run_all.py sets PATHWAY_SAVE_FIGURES=1)
RUNTIME_ONLY = ('SAVE_FIGURES', 'SHOW_PLOTS', 'FROZEN_RUN', 'QUICK_RUN')


PATHWAYS_MARK = '## Pathways (levers.py, pathways.py)'
PATHWAYS_EXCLUDED = ('SOURCES', 'LEVER_NAMES', 'STRATEGIES', 'STRATEGY_NAMES', 'LEVER_STRATEGY', 'SETTING_NAMES',
                     'BAND_TARGET', 'LEVER_PARAMETER', 'TL_NAMES', 'TL_DISCLAIMER', 'DENSER_MIX_V2_NOTE')


def pathways_section():
    """The generated Pathways section: register rows from levers.register() with the
    resolved values of outputs/data/pathways/levers.json, the theoretical limit TL from
    levers.register_tl() (outputs/data/pathways/theoretical_limit.json), then every setting in
    levers.py. Empty when levers.json does not exist yet."""
    import json
    import levers as LV
    lv_path = layout.data('pathways/levers.json', frozen=False)
    if not os.path.exists(lv_path):
        return []
    with open(lv_path) as f:
        lv = json.load(f)
    L = ['', PATHWAYS_MARK, '',
         'Resolved values from data/pathways/levers.json (MODEL v3.0.0 lever rule: Levels 1-4); Table 1 of the paper: '
         'docs/LEVERS_TABLE.md; methods as implemented: docs/METHODS_DRAFT.md (3. Pathways and the theoretical limit).',
         '',
         '| setting | value | basis |', '|---|---|---|']
    for r in LV.lever_table(lv):
        L.append(f"| {r['item']} ({r['strategy']}) | sub-rule {r['subrule']}: {r['anchor']}; Moderate {r['moderate']}; "
                 f"Ambitious {r['ambitious']}; TL {r['tl']} | {LV.SUBRULE_TEXT[r['subrule']]} |")
    for r in lv.get('tl_strength', []):
        L.append(f"| {r['item']} vs Ambitious | {r['tl']} vs {r['ambitious']} | asserted at least as strong: {r['ok']} |")
    L += ['', '### All settings in levers.py', '', '| setting | value |', '|---|---|']
    for k in sorted(vars(LV)):
        v = getattr(LV, k)
        if k.isupper() and isinstance(v, (bool, int, float, str, tuple, dict, type(None))) and k not in PATHWAYS_EXCLUDED:
            L.append(f'| `{k}` | `{v!r}` |')
    return L


def update_pathways_section():
    """Replace only the Pathways section of ASSUMPTIONS.md (the last section), leaving every
    baseline row byte-identical (run_all.py --pathways-only). Idempotent."""
    path = OUT_MD
    txt = open(path).read()
    head = txt[:txt.index(PATHWAYS_MARK)].rstrip('\n') + '\n' if PATHWAYS_MARK in txt else txt
    body = pathways_section()
    with open(path, 'w') as f:
        f.write(head + ('\n'.join(body[1:]) + '\n' if body else '').replace(PATHWAYS_MARK, '\n' + PATHWAYS_MARK, 1)
                if body else head)
    print(f'outputs/reports/ASSUMPTIONS.md: Pathways section {len(body)} lines')


def main():
    import projection
    from baseline_draft import TIMING_LIMITATIONS, LIMITATIONS, decarb_limitations, overbuild_limitations, register
    L = ['# Assumptions (generated by tools/assumptions.py; do not edit by hand)', '',
         'Basis labels: DATA (measured), LITERATURE (cited), DECISION (author), JUDGEMENT (not '
         'identifiable from data; bracketed by sensitivities in outputs/data/baseline/sensitivity_one_at_a_time.csv).', '',
         '## Baseline projection (projection.py)', '', '| setting | value | basis |', '|---|---|---|']
    L += [f'| {a} | {v} | {b} |' for a, v, b in register()]
    L += ['', '### Limitation of the 2026 overbuild rule', ''] + [f'- {x}' for x in overbuild_limitations()]
    L += ['', '### Limitations of the material decarbonisation', ''] + [f'- {x}' for x in decarb_limitations(projection.DECARB_MODE)]
    L += ['', '### Limitations of the time-resolved accounting and the A4-A5 path', ''] + [
        f'- {x}' for x in TIMING_LIMITATIONS]
    L += ['', '### Other limitations of the projection', ''] + [f'- {x}' for x in LIMITATIONS]
    L += ['', '### All settings in projection.py', '', '| setting | value |', '|---|---|']
    for k in sorted(vars(projection)):
        v = getattr(projection, k)
        if k.isupper() and not k.startswith(('FILE_', 'COL_', 'SHEET_')) and k not in ('ROOT_DIR', 'DATA_DIR', 'OUT_DIR', 'FIG_DIR', 'FACTORS_DIR') \
                and k not in RUNTIME_ONLY \
                and isinstance(v, (bool, int, float, str, tuple, type(None))):
            L.append(f'| `{k}` | `{v!r}` |')
    import boundaries
    L += ['', '## Planetary-boundary layer (AESA; boundaries.py)', '', '| setting | value | basis |', '|---|---|---|']
    L += [f'| {a} | {v} | {b} |' for a, v, b in boundaries.assumption_register()]
    L += ['', '### Limitations of the planetary-boundary layer (AESA)', ''] + [f'- {x}' for x in boundaries.LIMITATIONS]
    L += ['', '### All settings in boundaries.py', '', '| setting | value |', '|---|---|']
    for k in sorted(vars(boundaries)):
        v = getattr(boundaries, k)
        if k.isupper() and not k.startswith('FILE_') and k not in ('ROOT_DIR', 'DATA_DIR', 'OUT_DIR', 'FIG_DIR') \
                and k not in RUNTIME_ONLY \
                and isinstance(v, (bool, int, float, str, tuple, type(None))):
            L.append(f'| `{k}` | `{v!r}` |')
    L.append(f"| `SOURCE_PAIRS` | `{boundaries.SOURCE_PAIRS!r}` |")
    L += pathways_section()
    with open(layout.writing(OUT_MD), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(f'outputs/reports/ASSUMPTIONS.md: {len(L)} lines')


if __name__ == '__main__':
    if '--pathways-only' in sys.argv:
        update_pathways_section()
    else:
        main()
