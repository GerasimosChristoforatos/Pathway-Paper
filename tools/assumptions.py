"""Generate ASSUMPTIONS.md from the settings in Boss.py (A3) and PB.py. No value is typed
by hand: the register (setting, value, basis) comes from
tools/baseline_draft.register(), and the full settings table lists every
upper-case scalar setting in Boss.py as it is at run time.

    python tools/assumptions.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))


# display and run-time switches: not model settings, and their value depends on how
# the tool is launched (run_all.py sets PATHWAY_SAVE_FIGURES=1)
RUNTIME_ONLY = ('SAVE_FIGURES', 'SHOW_PLOTS', 'VERBOSE', 'FROZEN_RUN', 'QUICK_RUN')


PATHWAYS_MARK = '## Pathways (levers.py, pathways.py)'
PATHWAYS_EXCLUDED = ('SOURCES', 'LEVER_NAMES', 'LEVER_GROUP', 'PATHWAYS', 'PATHWAY_NAMES', 'SETTING_NAMES',
                     'BAND_TARGET', 'LEVER_PARAMETER', 'T_NAMES', 'T_DISCLAIMER')


def pathways_section():
    """The generated Pathways section (PATHWAYS v2): register rows from levers.register() with the
    resolved values of outputs/pathways/levers.json, then every scalar setting in levers.py.
    Empty when levers.json does not exist yet."""
    import json
    import levers as LV
    lv_path = os.path.join(ROOT, 'outputs', 'pathways', 'levers.json')
    if not os.path.exists(lv_path):
        return []
    with open(lv_path) as f:
        lv = json.load(f)
    L = ['', PATHWAYS_MARK, '',
         'Resolved values from outputs/pathways/levers.json; Table 1 of the paper: outputs/pathways/LEVERS_TABLE.md; '
         'methods as implemented: outputs/pathways/PATHWAYS_METHODS_DRAFT.md.', '', '| setting | value | basis |',
         '|---|---|---|']
    L += [f'| {a} | {v} | {b} |' for a, v, b in LV.register(lv)]
    t_path = os.path.join(ROOT, 'outputs', 'pathways', 't_limit.json')
    if os.path.exists(t_path):                     # PATHWAYS v3: the theoretical limit T
        with open(t_path) as f:
            L += [f'| {a} | {v} | {b} |' for a, v, b in LV.register_T(json.load(f))]
    L += ['', '### All settings in levers.py', '', '| setting | value |', '|---|---|']
    for k in sorted(vars(LV)):
        v = getattr(LV, k)
        if k.isupper() and isinstance(v, (bool, int, float, str, tuple, dict, type(None))) and k not in PATHWAYS_EXCLUDED:
            L.append(f'| `{k}` | `{v!r}` |')
    return L


def update_pathways_section():
    """Replace only the Pathways section of ASSUMPTIONS.md (the last section), leaving every
    baseline row byte-identical (run_all.py --pathways-only). Idempotent."""
    path = os.path.join(ROOT, 'ASSUMPTIONS.md')
    txt = open(path).read()
    head = txt[:txt.index(PATHWAYS_MARK)].rstrip('\n') + '\n' if PATHWAYS_MARK in txt else txt
    body = pathways_section()
    with open(path, 'w') as f:
        f.write(head + ('\n'.join(body[1:]) + '\n' if body else '').replace(PATHWAYS_MARK, '\n' + PATHWAYS_MARK, 1)
                if body else head)
    print(f'ASSUMPTIONS.md: Pathways section {len(body)} lines')


def main():
    import Boss
    from baseline_draft import TIMING_LIMITATIONS, LIMITATIONS, decarb_limitations, near_term_limitations, register
    L = ['# Assumptions (generated by tools/assumptions.py; do not edit by hand)', '',
         'Basis labels: DATA (measured), LITERATURE (cited), DECISION (author), JUDGEMENT (not '
         'identifiable from data; bracketed by sensitivities in outputs/sensitivity_oat.csv).', '',
         '## Register', '', '| setting | value | basis |', '|---|---|---|']
    L += [f'| {a} | {v} | {b} |' for a, v, b in register()]
    L += ['', '### Limitation of the near-term rule', ''] + [f'- {x}' for x in near_term_limitations()]
    L += ['', '### Limitations of the material decarbonisation', ''] + [f'- {x}' for x in decarb_limitations(Boss.DECARB_MODE)]
    L += ['', '### Limitations of the time-resolved accounting and the A4-A5 path', ''] + [
        f'- {x}' for x in TIMING_LIMITATIONS]
    L += ['', '### Other limitations of the baseline', ''] + [f'- {x}' for x in LIMITATIONS]
    L += ['', '## All settings in Boss.py', '', '| setting | value |', '|---|---|']
    for k in sorted(vars(Boss)):
        v = getattr(Boss, k)
        if k.isupper() and not k.startswith(('FILE_', 'COL_', 'SHEET_')) and k not in ('ROOT_DIR', 'DATA_DIR', 'OUT_DIR', 'FIG_DIR', 'FACTORS_DIR') \
                and k not in RUNTIME_ONLY \
                and isinstance(v, (bool, int, float, str, tuple, type(None))):
            L.append(f'| `{k}` | `{v!r}` |')
    import PB
    L += ['', '## Planetary-boundary layer (PB.py)', '', '| setting | value | basis |', '|---|---|---|']
    L += [f'| {a} | {v} | {b} |' for a, v, b in PB.assumption_register()]
    L += ['', '### Limitations of the planetary-boundary layer', ''] + [f'- {x}' for x in PB.LIMITATIONS]
    L += ['', '### All settings in PB.py', '', '| setting | value |', '|---|---|']
    for k in sorted(vars(PB)):
        v = getattr(PB, k)
        if k.isupper() and not k.startswith('FILE_') and k not in ('ROOT_DIR', 'DATA_DIR', 'OUT_DIR', 'FIG_DIR') \
                and k not in RUNTIME_ONLY \
                and isinstance(v, (bool, int, float, str, tuple, type(None))):
            L.append(f'| `{k}` | `{v!r}` |')
    L.append(f"| `SOURCE_PAIRS` | `{PB.SOURCE_PAIRS!r}` |")
    L += pathways_section()
    with open(os.path.join(ROOT, 'ASSUMPTIONS.md'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(f'ASSUMPTIONS.md: {len(L)} lines')


if __name__ == '__main__':
    if '--pathways-only' in sys.argv:
        update_pathways_section()
    else:
        main()
