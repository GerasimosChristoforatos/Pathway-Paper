"""Final check of the generated outputs (run_all.py, last step): stale terms of
earlier versions must not appear in any generated output or document of the
adopted and frozen runs: the storyline scenario of v1.0.2-v1.2 (S2 + damped mix
trend), the retired decarbonisation names (horup_material, horup_class_v1_1, "mix
effect only") and the comparison runs removed in baseline-pb-v3 (--compare-modes,
DECARB_MODES, decarb_modes). CHANGELOG.md records them and is not checked.

    python tools/check_outputs.py
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'outputs')
STORYLINE = re.compile(r'storyline|S2-held|S3-10-trend|damped mix trend|intensification continues|horup_material|'
                       r'horup_class|mix effect only|compare-modes|DECARB_MODES|decarb_modes', re.I)
EXCLUDED = ()
# PATHWAYS v2 (pathways.py): every output must exist after a run
PATHWAYS_OUTPUTS = ('HOOKS.md', 'pathways_runs.csv', 'pathways_annual.csv', 'pathways_bands.csv',
                    'shapley_pathways.csv', 'shapley_levers.csv', 'shapley_subsets.csv', 'backcast.json',
                    'solution_space.csv', 'levers.json', 'PATHWAYS_METHODS_DRAFT.md', 'LEVERS_TABLE.md')
PATHWAYS_FIGURES = ('pw_1_bands_by_pathway', 'pw_2_shapley_waterfall', 'pw_3_solution_space', 'pw_4_annual_SI',
                    'pw_5_envelope_SI', 'pw_6_L5_estimator_SI', 'pw_7_shapley_levers_SI')
# written by run_all after the tests step (checked here, not by tests/test_v2.py)
AFTER_TESTS = ('metrics.json', 'RESULTS.md', 'BASELINE_DRAFT.md', 'PB_METHODS_DRAFT.md', 'ASSUMPTIONS.md')


def generated_files(include_docs=True):
    files = [p for d in (OUT, os.path.join(OUT, 'frozen'), os.path.join(OUT, 'pathways'))
             for ext in ('*.md', '*.json', '*.csv')
             for p in glob.glob(os.path.join(d, ext))]
    files += [os.path.join(ROOT, f) for f in ('ASSUMPTIONS.md', 'FIGURES.md', 'README.md')]
    files = [p for p in files if os.path.basename(p) not in EXCLUDED]
    if os.environ.get('PATHWAY_QUICK') == '1':      # quick runs do not re-run the frozen PB step
        files = [p for p in files if not (os.path.dirname(p).endswith('frozen')
                                          and os.path.basename(p).startswith('pb_'))]
    if not include_docs:
        files = [p for p in files if os.path.basename(p) not in AFTER_TESTS]
    return files


def storyline_hits(include_docs=True):
    hits = {}
    for p in generated_files(include_docs):
        with open(p, encoding='utf-8') as f:
            for i, line in enumerate(f, 1):
                if STORYLINE.search(line):
                    hits.setdefault(os.path.relpath(p, ROOT), []).append(i)
    return hits


def pathways_missing():
    missing = [f'outputs/pathways/{f}' for f in PATHWAYS_OUTPUTS if not os.path.exists(os.path.join(OUT, 'pathways', f))]
    fig = os.path.join(OUT, 'figures')
    if os.path.isdir(fig):              # figures are regenerated by every run_all.py
        missing += [f'outputs/figures/{f}.png' for f in PATHWAYS_FIGURES if not os.path.exists(os.path.join(fig, f + '.png'))]
    return missing


def main():
    missing = pathways_missing()
    if missing:
        print(f'check_outputs: pathways outputs missing: {missing}')
        sys.exit(1)
    hits = storyline_hits()
    if hits:
        print(f'check_outputs: stale terms found in {hits}')
        sys.exit(1)
    print(f'check_outputs: no stale terms in {len(generated_files())} generated files; '
          f'{len(PATHWAYS_OUTPUTS)} pathways outputs and {len(PATHWAYS_FIGURES)} figures present')


if __name__ == '__main__':
    main()
