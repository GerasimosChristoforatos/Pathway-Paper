"""Design documents of MODEL v3.0.0, generated from the code that enforces them:

  docs/FIGURE_PLAN_v3.md   the figure registry of figure_plan.py: paper_main Fig1-Fig8, paper_extended ED1-ED14 and
                           EDT1, the diagnostics by group, the rules (sign, palette, boundaries, maintenance) and the
                           retired figures
  docs/RENAMING.md         section 11 (between the MODEL v3.0.0 markers): the lever, TL, pathway, band and file
                           renames of MODEL v3.0.0, from naming.py (LEVER_V2_1, TL_V2_1, PATHWAY_LEVERS, BANDS) and
                           figure_plan.RETIRED. Sections 1-10 were generated by tools/design_docs.py against the
                           MODEL v1-v2.1 registries and are kept as the historical record.

    python tools/design_docs_v3.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import figure_plan as FP  # noqa: E402
import naming as N  # noqa: E402

DOCS = os.path.join(ROOT, 'docs')
BEGIN = '<!-- MODEL v3.0.0 section: generated by tools/design_docs_v3.py -->'
END = '<!-- end of MODEL v3.0.0 section -->'


def table(head, rows):
    return ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + \
        ['| ' + ' | '.join(str(c).replace('|', '\\|') for c in r) + ' |' for r in rows]


def code(s):
    return f'`{s}`'


def figure_plan():
    L = ['# Figure plan, MODEL v3.0.0 (generated by tools/design_docs_v3.py from figure_plan.py; do not edit by hand)',
         '',
         'One registry (`figure_plan.py`) decides where every figure is written (`layout.figure`), which module of '
         '`figures/` draws it, and which data files it reads. **Compute / draw separation**: the model scripts write '
         'data only (tests/test_figures_v3.py greps them for plotting); `figures/` reads `outputs/data/` only, and '
         '`run_all.py --figures-only` checks that every data file is byte-identical before and after drawing.',
         '',
         '**Formats** follow the run profile (`runprofile.py`): light, PNG at 200 dpi with the footer "LIGHT RUN — '
         'n=1000", under `outputs/_light/`; full, vector PDF and PNG at 600 dpi under `outputs/`. '
         '`outputs/FIGURES.md` is written by `indexes.py` from the same registry and the figure audit records.',
         '',
         '**Sign rules** (`figures/draw.py`). Time series: positive bands stacked up from zero, negative bands '
         f"({', '.join(N.BANDS[b] for b in N.NEGATIVE_BANDS)}) stacked down from zero, the net a black line. "
         'Cumulative bars: each negative band an unfilled, unhatched segment outlined in its band colour, hanging '
         'from the top of the positive stack, so the bar ends at the net total, marked with a tick. Material and '
         'stage values are never negative (`draw.nonnegative` stops the run). Only the recent replacement surge is '
         'hatched. **Boundaries**: AR a solid line, AtP a dotted line, with the three zones below AtP, between AtP '
         'and AR and above AR, in every figure of PB_FIGURES: ' + ', '.join(FP.PB_FIGURES) + '. **Maintenance** '
         '(B2, B4) is drawn as its own layer only in ' + ', '.join(FP.MAINTENANCE_ALLOWED) + '. The palette is the '
         'registry of `figures/style.py` ([PALETTE.md](PALETTE.md)); no colour repeats within a group.',
         '']
    L += ['## Paper, main (`outputs/paper_main/`)', '']
    for h in FP.PAPER_MAIN:
        L += [f"### {h['id']}. {h['title']}", '',
              f"* File: `{h['file']}` ({'183' if h['width'] == 'double' else '89'} mm); drawn by `{h['module']}`",
              f"* Data: {', '.join(code(s) for s in h['source'])}",
              f"* Draft caption: {h['caption']}", '']
    L += ['## Paper, Extended Data (`outputs/paper_extended/`)', '']
    L += table(['id', 'file', 'title', 'data'],
               [[h['id'], code(h['file']), h['title'], ', '.join(code(s) for s in h['source'])]
                for h in FP.PAPER_EXTENDED])
    L += ['', 'Tables:', '']
    L += [f"* **{t['id']}. {t['title']}**: `{t['file']}.md` / `.csv`; data: "
          f"{', '.join(code(s) for s in t['source'])}" for t in FP.EXTENDED_TABLES]
    L += ['', '## Diagnostics (`outputs/diagnostics/<group>/`)', '']
    for g, rows in FP.DIAGNOSTICS.items():
        L += [f'### {g}', '']
        L += table(['file', 'content', 'module', 'data'],
                   [[code(r['file']) + (' (full profile only)' if r['file'] in FP.FULL_ONLY else ''), r['title'],
                     code(r['module']), ', '.join(code(s) for s in r['source'])] for r in rows])
        L += ['']
    L += ['## Retired in MODEL v3.0.0', '']
    L += table(['MODEL v2.1.2', 'MODEL v3.0.0'], [[code(k), v] for k, v in FP.RETIRED.items()])
    return L


def renaming_section():
    L = [BEGIN, '', '## 11. MODEL v3.0.0 renaming', '',
         'Sections 1-10 are the record of MODEL v1.0.0-v2.1.2 (tools/design_docs.py). MODEL v3.0.0 renumbers the '
         'levers and the theoretical-limit components, regroups the pathways, adds three negative demand bands and '
         'replaces the paper / Extended Data / key-figure folders. Where a v3 label differs from section 1, the v3 '
         'label holds.', '',
         '### Levers (MODEL v2.1 -> MODEL v3.0.0)', '']
    L += table(['MODEL v2.1', 'MODEL v3.0.0'], [[k, v] for k, v in N.LEVER_V2_1.items()])
    L += ['', '### Levers and pathway families of MODEL v3.0.0', '']
    L += table(['id', 'label', 'pathway', 'Ambitious sub-rule', 'limit'],
               [[L_, N.LEVERS[L_], f"{N.LEVER_PATHWAY[L_]} {N.PATHWAYS[N.LEVER_PATHWAY[L_]]}", N.LEVER_SUBRULE[L_],
                 f"TL{L_[1:]} {N.TL[f'TL{L_[1:]}']}"] for L_ in N.LEVERS])
    L += ['', 'Sub-rules: A, case-study distribution (Harrell-Davis q0.15); B, best value ever observed in New Zealand; '
          'C, published reference value. Moderate is the exact midpoint of the native parameter between the Reference '
          '(Level 1) and Ambitious (Level 3); TLn is Level 4 of Ln and at least as strong as Ambitious.', '',
          'Levels: ' + '; '.join(f'`{k}` {v}' for k, v in N.LEVELS.items()) + '.', '',
          '### Theoretical-limit components (MODEL v2.1 -> MODEL v3.0.0)', '']
    L += table(['MODEL v2.1', 'MODEL v3.0.0'], [[k, v] for k, v in N.TL_V2_1.items()])
    L += ['', '### Demand bands added or relabelled', '']
    L += table(['id', 'MODEL v3.0.0 label', 'note'],
               [[code('overbuild_absorbed'), N.BANDS['overbuild_absorbed'], 'new; negative (Reference absorbs the '
                 '2026 overbuild by 2035)'],
                [code('unconsented'), N.BANDS['unconsented'], 'new; negative (split from the replacement band)'],
                [code('replacement'), N.BANDS['replacement'], 'relabelled from "Replacement": demolition only'],
                [code('released_tl'), N.BANDS['released_tl'], 'new; negative (TL only)']])
    L += ['', '### Output folders and figures', '']
    L += table(['MODEL v2.1.2', 'MODEL v3.0.0'], [[code(k), v] for k, v in FP.RETIRED.items()])
    L += ['', 'New folders: `outputs/paper_main/` (Fig1-Fig8), `outputs/paper_extended/` (ED1-ED14, EDT1), '
          '`outputs/diagnostics/{calibration, validation, boundaries, pathways, montecarlo, sensitivity}`, '
          '`outputs/FIGURES.md`, `outputs/run_meta.json`; the light profile mirrors the tree under `outputs/_light/` '
          'and `--reference-legacy` writes under `outputs/_legacy/`. Full list: [FIGURE_PLAN_v3.md](FIGURE_PLAN_v3.md).',
          '', END]
    return L


def main():
    L = figure_plan()
    with open(os.path.join(DOCS, 'FIGURE_PLAN_v3.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print(f'design_docs_v3: docs/FIGURE_PLAN_v3.md ({len(L)} lines)')
    path = os.path.join(DOCS, 'RENAMING.md')
    text = open(path, encoding='utf-8').read()
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip('\n') + '\n'
    sec = renaming_section()
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text.rstrip('\n') + '\n\n' + '\n'.join(sec) + '\n')
    print(f'design_docs_v3: docs/RENAMING.md section 11 ({len(sec)} lines)')


if __name__ == '__main__':
    main()
