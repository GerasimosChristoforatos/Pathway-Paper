"""The methods draft of the model (MODEL v3.1.0): outputs/reports/METHODS_DRAFT.md and LEVERS_TABLE.md (Table 1), copied
to docs/METHODS_DRAFT.md and docs/LEVERS_TABLE.md with the run profile named in their header.

    python tools/methods.py          (run_all.py runs it after the data)

Four parts, each generated from the data files by its own module (no number is typed by hand):

  1. Baseline projection                       tools/baseline_draft.py   lines()
  2. Planetary-boundary layer (AESA)           tools/pb_methods.py       lines()
  3. Pathways and the theoretical limit        tools/pathways_methods.py lines()
  4. Emissions accounting, release accounting  tools/accounting_methods.py lines()

The parts keep their own section headings, one level down; reader-facing ranges, m² and CO₂e
are typeset as in the headline captions (naming.typeset).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import layout  # noqa: E402
import naming as N  # noqa: E402

PARTS = [('1. Baseline projection', 'baseline_draft'),
         ('2. Planetary-boundary layer (AESA)', 'pb_methods'),
         ('3. Pathways and the theoretical limit', 'pathways_methods'),
         ('4. Emissions accounting, release accounting and the history (MODEL v3.1.0)', 'accounting_methods')]
# inline code, URLs and DOIs are never typeset (their hyphens are not ranges)
VERBATIM = re.compile(r'(`[^`]*`|https?://\S+|\bdoi:\S+|\b10\.\d{4,9}/\S+)')


def demote(line):
    return '#' + line if line.startswith('#') else line


def typeset(line):
    """Typeset prose only: inline code, URLs, DOIs and table separators keep their characters."""
    if set(line.strip()) <= set('|-: '):
        return line
    parts = VERBATIM.split(line)                     # odd items are the verbatim tokens
    return ''.join(p if i % 2 else N.typeset(p) for i, p in enumerate(parts))


def lines():
    import importlib
    import runprofile
    out = ['# Methods (DRAFT; generated by tools/methods.py from the data files, do not edit by hand)', '',
           f'Run profile: {runprofile.name()} ({runprofile.get("n_draws"):,} Monte Carlo draws). Draft text of the '
           'methods and their results, in four parts generated from the data files (the deterministic numbers do not '
           'depend on the profile). Every figure: FIGURES.md; every output file: INDEX.md. References: '
           'docs/REFERENCES.md.', '']
    out += ['## Contents', ''] + [f'* {title}' for title, _ in PARTS] + ['']
    for title, module in PARTS:
        part = importlib.import_module(module).lines()
        out += [f'## {title}', ''] + [typeset(demote(x)) for x in part] + ['']
    return out


def main():
    import shutil
    import pathways_methods
    path = layout.writing(layout.report('METHODS_DRAFT.md', frozen=False))
    L = lines()
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L).rstrip('\n') + '\n')
    pathways_methods.main()
    for name in ('METHODS_DRAFT.md', 'LEVERS_TABLE.md'):
        shutil.copyfile(layout.report(name, frozen=False), os.path.join(ROOT, 'docs', name))
    print(f'methods: {os.path.relpath(path, ROOT)} ({len(L)} lines); copied with LEVERS_TABLE.md to docs/')


if __name__ == '__main__':
    main()
