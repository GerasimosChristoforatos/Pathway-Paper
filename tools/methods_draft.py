"""The methods draft of the model, one document (MODEL v1.0.0): outputs/reports/METHODS_DRAFT.md.

    python tools/methods_draft.py          (run_all.py runs it after the data and figures)

Three parts, each generated from the data files by its own module (no number is typed by hand):

  1. Baseline projection                       tools/baseline_draft.py   lines()
  2. Planetary-boundary layer (AESA)           tools/pb_methods.py       lines()
  3. Pathways and the theoretical limit        tools/pathways_methods.py lines()

The parts keep their own section headings, one level down; reader-facing ranges, m² and CO₂e
are typeset as in the headline captions (naming.typeset).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import layout  # noqa: E402
import naming as N  # noqa: E402

PARTS = [('1. Baseline projection', 'baseline_draft'),
         ('2. Planetary-boundary layer (AESA)', 'pb_methods'),
         ('3. Pathways and the theoretical limit', 'pathways_methods')]
# inline code, URLs and DOIs are never typeset (their hyphens are not ranges)
VERBATIM = re.compile(r'(`[^`]*`|https?://\S+|\bdoi:\S+|\b10\.\d{4,9}/\S+)')


def demote(line):
    return '#' + line if line.startswith('#') else line


def typeset(line):
    """Typeset prose only: inline code, URLs, DOIs and table separators keep their characters."""
    if set(line.strip()) <= set('|-: '):
        return line
    parts = VERBATIM.split(line)                     # odd items are the verbatim tokens
    return ''.join(p if i % 2 else N.typeset(p) for i, p in enumerate(parts))


def lines():
    import importlib
    out = ['# Methods (DRAFT; generated by tools/methods_draft.py from the data files, do not edit by hand)', '',
           'Draft text of the methods and their results, in three parts generated from outputs/data/ (the numbers '
           'are locked by tests/test_regression_model_v1.py and tests/test_regression_model_v2.py). The figures of the '
           'paper: outputs/paper/PAPER.md; Extended Data: outputs/extended_data/EXTENDED_DATA.md; '
           'every other figure: outputs/diagnostics/DIAGNOSTICS.md; every output file: outputs/INDEX.md.', '']
    out += ['## Contents', ''] + [f'* {title}' for title, _ in PARTS] + ['']
    for title, module in PARTS:
        part = importlib.import_module(module).lines()
        out += [f'## {title}', ''] + [typeset(demote(x)) for x in part] + ['']
    return out


def main():
    path = layout.writing(layout.report('METHODS_DRAFT.md', frozen=False))
    L = lines()
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L).rstrip('\n') + '\n')
    print(f'methods_draft: {os.path.relpath(path, ROOT)} ({len(L)} lines)')


if __name__ == '__main__':
    main()
