"""Generate outputs/pathways/PATHWAYS_METHODS_DRAFT.md: the PATHWAYS v1 layer as implemented
(equations, parameter table with sources, results tables, checks, limitations). Every
number is read from outputs/pathways/ (levers.json, pathways_runs.csv, shapley.csv,
backcast.json) or from the settings in levers.py; nothing is typed by hand.

    python tools/pathways_methods.py
"""
import json
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'outputs', 'pathways')
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))


def table(head, rows):
    L = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    L += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return L


def main():
    import levers as LV
    p = json.load(open(os.path.join(OUT, 'levers.json')))
    runs = pd.read_csv(os.path.join(OUT, 'pathways_runs.csv'))
    sh = pd.read_csv(os.path.join(OUT, 'shapley.csv'))
    bc = json.load(open(os.path.join(OUT, 'backcast.json')))
    ref = runs[(runs['scenario'] == 'S3-10') & (runs['ramp_full'] == LV.RAMP_FULL)].set_index('run')
    p0 = ref.loc['P0']
    L = ['# PATHWAYS v1: methods (DRAFT; generated by tools/pathways_methods.py, do not edit by hand)', '']
    if p['run_mode'] != 'full':
        L += [f"> **{p['run_mode']}** (run_all.py --quick).", '']
    L += [
        'Five levers on new residential construction in New Zealand, 2026-2050, applied to the baseline projection '
        '(baseline-pb-v3.1, reference replacement scenario S3-10) and assessed against the climate-change boundaries '
        'of the planetary-boundary layer (acquired rights, AR; ability to pay, AtP). The model is unchanged: '
        '`pathways.py` re-calls `engine.forward()` with copies of the reference inputs modified by `levers.py` '
        '(hooks: outputs/pathways/HOOKS.md). With every lever off the run reproduces the reference run '
        f"(maximum relative difference {p['identity_max_rel_diff']:.1e} over annual carbon, upfront, in-window "
        'replacements & repaints, floor area by typology, demand bands, committed range and cumulative LoE; '
        'tests/test_pathways.py).', '',
        '## Conventions', '',
        f"* Years: 2026 is observed (consented floor area fixed) and no lever changes it. A lever at full strength "
        f"moves a quantity from its baseline value b to its target x as b + w(y) (x - b), with "
        f"w(y) = clip((y - 2026) / ({p['ramp']['full']} - 2026), 0, 1): 1/9 in 2027, full from {p['ramp']['full']}. "
        f"Sensitivity (P3): full by {p['ramp']['full_sensitivity']}.",
        '* Near-term market excess (the observed 2026 building above the requirement, fading at rho): frozen at '
        'the baseline path, in dwellings, in every run except where L2 absorbs the surplus. It is the observed 2026 '
        'pipeline, not demand, so a lever on demand does not change it.',
        '* Bundles: P1 Avoid = L1 + L2 + L3; P2 Shift + Improve = L4 + L5; P3 = all five; each at Moderate (M) '
        'and Ambitious (A). Scenarios S1 (Low) and S2 (High) bound P0 and P3 (full Boss runs with '
        '`REPLACEMENT_SCENARIO` changed; the levers act on each run\'s own inputs).',
        '* Accounting as the baseline (time-resolved): within-window carbon = upfront (A1-A5 + soil) in the '
        'construction year + replacements & repaints (B2, B4) occurring 2026-2050; later events and all C1-C4 of '
        'the 2026-2050 cohorts are committed after 2050 (range: lower with the 2050 factors held, upper at 2025 '
        'factors; `events.committed` with each run\'s floor area by typology).', '',
        '## Levers as implemented (levers.py)', '',
        '    L1  size_t(y)       = size_ref_t · (1 − w(y) c_t)',
        '    L2  v(y)            = v0 + w(y) (v* − v0);   join = market_excess(E_nojoin, O26, ρ, 2027, surplus, a)',
        '    L3  demol(y)        = demol · (1 − w(y) d);  resid(y) = resid_LR + (resid_S3(y) − resid_LR)(1 − w(y) d)',
        '    L4  att(y)          = att0 + w(y)(att* − att0); Δ to townhouses / apartments ∝ their held shares; detached −Δ',
        '    L5  A1-A3_t(y)      = [1 − w(y)(1 − r_t)] · (A1-A3_t,2025 − R13_t(y))   (A4-A5, events, C1-C4, soil unchanged)', '',
        'size_ref: realised new-dwelling size (consented floor area / dwellings, mean of 2023-2025); v0: the 2023 '
        'census vacancy held by the baseline; ρ, O26, gap reference: as the baseline near-term rule; resid_LR: the '
        'long-run residual (long-run net replacement − BRANZ demolition rate); resid_S3: the S3-10 residual path; '
        'R13: the decarbonisation of A1-A3 (Horup et al. 2025, item level). L2 lowers vacancy through the stock '
        'identity: while v falls (2027-2035) the vacancy-change term releases existing dwellings once; afterwards '
        'only the lower vacancy allowance on new households remains. L4 changes the blended dwelling size and '
        'occupancy load factor through the shares (no separate size change). L5 keeps decarbonisation on top of the '
        'best-practice ratio.', '',
        '## Parameters and sources', '']
    L += table(['setting', 'value', 'basis'], LV.register(p))
    L += ['', '### Resolved data targets (levers.json)', '']
    L1 = p['L1']
    L += table(['typology', 'size_ref 2023-25 (m²)', '1991-95 size (m²)', 'L1 M cut', 'L1 A cut', 'L1 A size (m²)',
                'L5 r M', 'L5 r A', 'L5 M cases', 'L5 A case'],
               [[t, f"{L1['size_ref'][t]:.1f}", f"{L1['size_1991_1995'][t]:.1f}", f"{100 * L1['c']['M'][t]:.1f}%",
                 f"{100 * L1['c']['A'][t]:.2f}%" + (' (held)' if t in L1['held_A'] else ''),
                 f"{L1['target_size']['A'][t]:.1f}", f"{p['L5']['r']['M'][t]:.3f}", f"{p['L5']['r']['A'][t]:.3f}",
                 ', '.join(p['L5']['cases'][t]['cases_M']) or 'held', p['L5']['cases'][t]['case_A'] or 'held']
                for t in L1['size_ref']])
    L4 = p['L4']
    L += ['', f"Attached floor-area share: baseline (held 2022-2026 average) {100 * L4['baseline_attached']:.2f}%; "
          f"observed peak 1991-2026 {100 * L4['target']['M']:.2f}% in {L4['peak_year']} (M); baseline + 16 points "
          f"{100 * L4['target']['A']:.2f}% (A). 2026 counted as the model's observed 2026 mix (latest 12 months, "
          f"{100 * L4['attached_by_year']['2026']:.2f}%; calendar January-July 2026: "
          f"{100 * L4['attached_2026_calendar_ytd']:.2f}%).",
          f"Pooled 2025 A1-A3 recomputed from factors_building.csv equals the model's pooled factor to "
          f"{p['L5']['pooled_check_max_abs']:.1e} kg/m².", '']
    L += ['## Attribution', '',
          'Shapley value of lever i for the reduction v(∅) − v(N), over all 2^5 = 32 subsets S of the levers N (each '
          'subset a full run):', '',
          '    φ_i = Σ_{S ⊆ N∖{i}} |S|! (5 − |S| − 1)! / 5! · [v(S) − v(S ∪ {i})]', '',
          'computed in exact rational arithmetic on the run values, so Σ_i φ_i = v(∅) − v(N) = P0 − P3 exactly '
          '(tested). v = cumulative within-window carbon (kt) or cumulative LoE AR. The waterfall (pw_1) adds the '
          'levers in the fixed order L1 → L5 (Avoid → Shift → Improve); its steps are order-dependent.', '',
          '## AESA gap', '',
          'Boundaries B_AR(t), B_AtP(t) for S3-10 from outputs/pb_annual.csv (no lever changes population; every '
          'scenario shares the population path). Cumulative LoE = Σ I(t) / Σ B(t) over 2026-2050 '
          '(aesa.cumulative_loe); remaining reduction needed = 1 − 1/LoE.', '',
          '**Back-cast.** I(t; k) = F(t) + k · G(t), where F is the 2026 cohort (its upfront and its in-window '
          'replacements & repaints) and G the 2027-2050 cohorts (upfront and in-window events); scaling the floor '
          'area of every 2027-2050 cohort by k scales G (the typology mix and the replacement share, hence the soil '
          'share, are unchanged). k solves Σ I(t; k) = Σ B_AR(t) (scipy.optimize.brentq on [0, 1], xtol 1e-15; '
          'checked against the closed form). For AtP the minimum attainable cumulative LoE is Σ F / Σ B_AtP (k = 0).', '',
          '**Solution space** (after Horup et al. 2025, Fig. 6): I(t; d, i) = F(t) + (1 − d)[(1 − i) G_ns(t) + '
          'G_soil(t)] on P0, with d the uniform cut of 2027-2050 floor area and i the uniform cut of non-soil carbon '
          'per m² of the 2027-2050 cohorts (soil and 2026 not cut by i). Bundles are placed at d = 1 − GFA_P / GFA_0 '
          'and i = 1 − (C_P / GFA_P) / (C_0 / GFA_0) (2027-2050 cohorts, C non-soil within the window); because the '
          'levers also change the soil-bearing share, the grid value at a marker differs slightly from the run '
          '(both in backcast.json).', '',
          '## Results (S3-10)', '']
    rows = []
    for name in ['P0'] + [f'{x}-{s}' for x in LV.LEVERS for s in LV.SETTINGS] + \
            [f'{P}-{s}' for P in ('P1', 'P2', 'P3') for s in LV.SETTINGS]:
        r = ref.loc[name]
        rows.append([name, f"{r['gfa_Mm2']:.2f}", f"{r['carbon_kt']:,.0f}",
                     f"{r['committed_lower_kt']:,.0f}-{r['committed_upper_kt']:,.0f}", f"{r['LoE_AR']:.2f}",
                     f"{r['LoE_AtP']:.1f}", f"{100 * r['remaining_reduction_AR']:.1f}%",
                     f"{r['delta_carbon_kt_vs_P0_pct']:+.1f}%", f"{r['dwellings_built']:,.0f}",
                     f"{r['mean_dwelling_size_m2']:.1f}", f"{r['carbon_per_m2_kg']:.1f}",
                     f"{r['carbon_per_dwelling_t']:.1f}", f"{100 * r['implied_vacancy_min']:.2f}%"])
    L += table(['run', 'floor area (Mm²)', 'carbon 2026-2050 (kt)', 'committed after 2050 (kt)', 'LoE AR', 'LoE AtP',
                'AR reduction still needed', 'carbon vs P0', 'dwellings built', 'mean size (m²)', 'kg CO₂e/m²',
                't CO₂e/dwelling', 'min implied vacancy'], rows)
    L += ['', '### Shapley attribution of P0 − P3', '']
    srows = []
    for L_ in LV.LEVERS:
        line = [f'{L_} {LV.LEVER_NAMES[L_]} ({LV.LEVER_GROUP[L_]})']
        for s in LV.SETTINGS:
            for metric, fmt in (('carbon_kt', '{:,.0f}'), ('LoE_AR', '{:.3f}')):
                x = sh[(sh['setting'] == s) & (sh['metric'] == metric) & (sh['method'] == 'shapley') & (sh['lever'] == L_)].iloc[0]
                line.append(fmt.format(x['reduction']) + (f" ({100 * x['share_of_P0_minus_P3']:.0f}%)" if metric == 'carbon_kt' else ''))
        srows.append(line)
    srows.append(['P0 − P3'] + [f"{p0['carbon_kt'] - ref.loc['P3-M', 'carbon_kt']:,.0f}",
                                f"{p0['LoE_AR'] - ref.loc['P3-M', 'LoE_AR']:.3f}",
                                f"{p0['carbon_kt'] - ref.loc['P3-A', 'carbon_kt']:,.0f}",
                                f"{p0['LoE_AR'] - ref.loc['P3-A', 'LoE_AR']:.3f}"])
    L += table(['lever', 'M: carbon (kt)', 'M: LoE AR', 'A: carbon (kt)', 'A: LoE AR'], srows)
    b3, b0 = bc['P3_A'], bc['P0']
    L += ['', '### Back-cast', '',
          f"Cumulative boundaries 2026-2050: AR {bc['B_AR_kt']:,.0f} kt, AtP {bc['B_AtP_kt']:,.0f} kt. The 2026 "
          f"cohort alone (construction and its in-window events, fixed) emits {b3['carbon_fixed_2026_cohort_kt']:,.0f} kt.", '']
    L += table(['', 'P3-A', 'P0'],
               [['LoE AR at k = 1', f"{b3['LoE_AR_at_k1']:.3f}", f"{b0['LoE_AR_at_k1']:.3f}"],
                ['k for cumulative LoE AR = 1', f"{b3['k_AR']:.4f}", f"{b0['k_AR']:.4f}"],
                ['cut of 2027-2050 construction (1 − k)', f"{100 * b3['cut_AR']:.1f}%", f"{100 * b0['cut_AR']:.1f}%"],
                ['2027-2050 floor area at k (Mm²)', f"{b3['gfa_2027_2050_at_k_Mm2']:.2f}", f"{b0['gfa_2027_2050_at_k_Mm2']:.2f}"],
                ['equivalent floor-area cut vs P0 (2027-2050)', f"{100 * b3['equivalent_cut_vs_P0_floor_area']:.1f}%", '-'],
                ['equivalent carbon cut vs P0 (2027-2050 cohorts)', f"{100 * b3['equivalent_cut_vs_P0_carbon_2027_2050_cohorts']:.1f}%", '-'],
                ['minimum LoE AtP (k = 0)', f"{b3['LoE_AtP_min_k0']:.3f}", f"{b0['LoE_AtP_min_k0']:.3f}"]])
    L += ['', f"AtP: {bc['AtP_note']} (the minimum cumulative LoE AtP with no construction after 2026 is "
          f"{b3['LoE_AtP_min_k0']:.2f}).", '', '### Envelope and ramp sensitivity', '']
    erows = []
    for scen in ('S1', 'S3-10', 'S2'):
        for name in ('P0', 'P3-M', 'P3-A', f'P3-M-ramp{LV.RAMP_FULL_SENS}', f'P3-A-ramp{LV.RAMP_FULL_SENS}'):
            r = runs[(runs['scenario'] == scen) & (runs['run'] == name)].iloc[0]
            erows.append([scen, name, f"{r['gfa_Mm2']:.2f}", f"{r['carbon_kt']:,.0f}", f"{r['LoE_AR']:.2f}",
                          f"{r['LoE_AtP']:.1f}", f"{r['delta_carbon_kt_vs_P0_pct']:+.1f}%"])
    L += table(['scenario', 'run', 'floor area (Mm²)', 'carbon (kt)', 'LoE AR', 'LoE AtP', 'carbon vs P0 of the scenario'], erows)
    L += ['', '## Checks (tests/test_pathways.py)', '',
          '* P0 = reference run (≤ 1e-9 relative): annual carbon, upfront, in-window B, floor area by typology, demand '
          'bands (boss_results.json), committed range, cumulative LoE AR / AtP (pb_results.json); S1 and S2 P0 = the '
          'PB scenario runs.',
          '* Each lever at zero strength = the baseline; 2026 identical in every run; lever functions never modify '
          'their inputs.',
          '* Shapley efficiency exact; D ≥ S × OLF in every year of every run (engine `extra_clip` = 0); implied '
          f"vacancy ≥ {100 * p['L2']['floor']:.1f}%; no negative dwellings built; back-cast LoE AR = 1 (≤ 1e-9).",
          '* Baseline outputs byte-identical to tag baseline-PB_v3.1 outside outputs/pathways/.', '',
          '## Limitations', '',
          '* L3 lifetime extension is an upper bound: the carbon of renovating the buildings kept in use is not '
          'modelled (Napiontek et al. 2025, Resour. Conserv. Recycl. 215, 108117).',
          f"* L1 Ambitious is weaker than Moderate: the 1991-1995 realised sizes of townhouses "
          f"({L1['size_1991_1995']['Townhouses']:.1f} m²) and apartments ({L1['size_1991_1995']['Apartments']:.1f} m²) "
          f"exceed the 2023-2025 sizes, so both are held and only detached dwellings are cut "
          f"({100 * L1['c']['A']['Detached']:.2f}%).",
          f"* L5 Ambitious rests on a single case study per typology (detached {p['L5']['cases']['Detached']['case_A']}, "
          f"A1-A3 {p['L5']['cases']['Detached']['target_A']:.1f} kg/m² against the pooled "
          f"{p['L5']['cases']['Detached']['pooled_a13']:.1f}); apartments are held (one independent case study). "
          'The ratio is applied to the pooled A1-A3 of every item, so the best-practice material mix is assumed '
          'transferable to the whole typology.',
          f"* L2: v0 = {100 * p['L2']['v0']:.2f}% is the published 2023 empty-dwelling share while the target range "
          f"({100 * p['L2']['census_consistent_min']:.2f}-{100 * p['L2']['census_consistent_max']:.2f}%) is on a consistent "
          'definition (pooled 2018/2023 empty share of unoccupied); the targets are rounded to 0.1 point. Vacancy '
          'reduction acts once, through the stock identity, while the rate falls.',
          '* L4 changes the typology shares only: dwelling size and occupancy load factor per typology, and the '
          'per-typology carbon and soil factors, stay as in the baseline.',
          '* The near-term excess is frozen in dwellings, so its floor area follows L1 and L4 through the blended size.',
          '* Each lever is a parameter change on the baseline model; no behavioural, market or rebound response is '
          'modelled; interactions between levers are those of the model (attributed by Shapley values).',
          '* The pathways are deterministic (median demographics); the Monte Carlo and the boundary sensitivities of '
          'the baseline are not re-run for them. Boundaries are static (PB layer limitations apply).',
          '* Omitted in v1: ' + '; '.join(f'{a} ({b})' for a, b in LV.OMITTED) + '.', '',
          '## Sources', ''] + [f'* {v}' for v in p['sources'].values()]
    path = os.path.join(OUT, 'PATHWAYS_METHODS_DRAFT.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print(f'pathways_methods: {path} ({len(L)} lines)')


def sections():
    """The generated Pathways sections outside outputs/pathways/: FIGURES.md (pathways.update_figures_md)
    and ASSUMPTIONS.md (tools/assumptions.update_pathways_section). Both replace only their own
    section and are idempotent."""
    import pathways
    import assumptions
    pathways.update_figures_md()
    assumptions.update_pathways_section()


if __name__ == '__main__':
    main()
    if '--sections' in sys.argv:
        sections()
