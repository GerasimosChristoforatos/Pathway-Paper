    "'rule' column): the Reference is current practice held (2023 / 2025 values; business-as-usual technology change "
    'applies in every run); Moderate is the midpoint of the Reference and Ambitious (exact for every lever); Ambitious '
    'is a documented frontier, achieved somewhere or projected by an authority, and cited; the theoretical limit is '
    'the logical bound where the lever has one (zero vacancy, zero space beyond the occupied area, no demolition, 100% '
    'brownfield, zero A4-A5), otherwise the best value observed (TL1 household size; the lowest-carbon NZ case study '
    'for materials). TL A4-A5 = 0 is a theoretical bound: construction waste cannot strictly reach zero, and LCAQuick '
    'does not split A4 from A5. Ambitious takes the first applicable sub-rule: A, a case-study distribution exists: the Harrell-Davis q0.15 '
    'quantile of the pooled scale-free case ratios (the top-15% convention of the EU Taxonomy, Delegated Regulation '
    '2021/2139, Annex I s. 7.7), with a percentile bootstrap interval; B, an NZ record with no structural trend exists: '
    'the best value ever observed in NZ; C, otherwise: a published reference value (official projection > legislated '
    'target > peer-reviewed scenario > peer-country value). Moderate is the exact midpoint between the Reference and '
    'Ambitious in the lever\'s native parameter (per year for the path levers L1 and L9). TL is the definitional zero '
    'or full where one exists, else the best single observation, and is asserted at least as strong as Ambitious. '
