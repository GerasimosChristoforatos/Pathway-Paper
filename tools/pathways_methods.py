DATA = layout.data('pathways', frozen=False)


def _js(name):
    with open(os.path.join(DATA, name)) as f:
        return json.load(f)


def _csv(name):
    import pandas as pd
    return pd.read_csv(os.path.join(DATA, name))


TABLE1_HEADER = (
    'Ambition levels follow the 2050 Pathways Calculator (DECC 2010; DESNZ 2023) and EUCalc (D2.5, 2020): Reference = '
    'Level 1, Moderate = Level 2, Ambitious = Level 3, theoretical limit (TL) = Level 4. Ambitious is the best value '
    'already achieved, by the first applicable sub-rule: A, a case-study distribution exists: the Harrell-Davis q0.15 '
    'quantile of the pooled scale-free case ratios (the top-15% convention of the EU Taxonomy, Delegated Regulation '
    '2021/2139, Annex I s. 7.7), with a percentile bootstrap interval; B, an NZ record with no structural trend exists: '
    'the best value ever observed in NZ; C, otherwise: a published reference value (official projection > legislated '
    'target > peer-reviewed scenario > peer-country value). Moderate is the exact midpoint between the Reference and '
    'Ambitious in the lever\'s native parameter (per year for the path levers L3 and L7). TL is the definitional zero '
    'or full where one exists, else the best single observation, and is asserted at least as strong as Ambitious. '
    'Every level moves from the Reference along the normalised logistic 2026 -> 2035 (midpoint 2030.5, k = ln(81)/6).')


def table(head, rows):
    return ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + ['| ' + ' | '.join(str(c) for c in r) + ' |'
                                                                          for r in rows]


def levers_table(p=None):
    p = p or _js('levers.json')
    rows = LV.lever_table(p)
    L = ['# Table 1. The nine levers and their levels (generated by tools/pathways_methods.py; do not edit)', '',
         TABLE1_HEADER, '']
    L += table(['Lever', 'Pathway', 'Sub-rule', 'Anchor (Ambitious)', 'Native parameter', 'Moderate (Level 2)',
                'Ambitious (Level 3)', 'TL (Level 4)', 'Band targeted'],
               [[r['item'], r['pathway'], r['subrule'], r['anchor'], r['parameter'], r['moderate'], r['ambitious'],
                 r['tl'], r['band']] for r in rows])
    L += ['', 'Sources: ' + '; '.join(f'{k}: {v}' for k, v in LV.SOURCES.items()), '']
    return L


def _r(df, run, col, scen='REF'):
    return float(df[(df['scenario'] == scen) & (df['run'] == run)][col].iloc[0])


