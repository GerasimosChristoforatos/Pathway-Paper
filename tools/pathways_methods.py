def table1_main_check(p=None):
    """The structural facts Table 1 states, checked against levers.json (STOP on a mismatch): the strategy of each
    lever, the L1 propensities, the 1996 vacancy minimum, zero vacancy / no demolition / full brownfield at TL, the
    top-15% (HD q0.15) Ambitious of L5 and L8, L9 at zero in 2050 and the TL1 1991 level."""
    import numpy as np
    p = p or _js('levers.json')
    strat = {L: N.STRATEGIES[St].split()[0] for St, ls in N.STRATEGY_LEVERS.items() for L in ls}
    bad = [L for L, row in TABLE1_MAIN.items() if strat[L] != row[1]]
    checks = {
        'strategy (PAS 2080) as naming.STRATEGY_LEVERS': not bad,
        'L1 Reference A, Ambitious B': list(p['L1']['variants']) == ['A', 'B'] and 'propensity B' in p['L1']['source'],
        'L1 TL = the 1991 household size': int(p['L1']['tl_year']) == 1991,
        'L2 Ambitious = the 1996 census minimum': '1996' in p['L2']['anchor'],
        'L2 TL = zero vacancy': float(p['L2']['tl']) == 0.0,
        'L3 Ambitious = 40% fewer demolitions': abs(float(p['L3']['d']['ambitious']) - 0.40) < 1e-12,
        'L3 TL = no demolition': float(p['L3']['tl']['d_demolition']) == 1.0,
        'L5 / L8 Ambitious = HD q0.15': all('q0.15' in p[L]['anchor'] for L in ('L5', 'L8')),
        'L6 TL = 100% brownfield': float(p['L6']['tl']) == 1.0,
        'L9 Ambitious = 0 in 2050, TL = 0': abs(float(p['L9']['target']['ambitious']['2050'])) < 1e-12
        and float(p['L9']['tl']) == 0.0,
        'L9 Reference = 1% per year decline': abs(float(p['L9']['target']['reference']['2026'])
                                                  - float(np.exp(-0.01))) < 1e-12,
    }
    failed = [k for k, v in checks.items() if v is False]
    if failed:
        raise SystemExit(f'STOP: Table 1 (main) does not match levers.json: {failed}; strategies {bad}')
    return checks


