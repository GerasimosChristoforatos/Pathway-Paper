def table(head, rows):
    return ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + ['| ' + ' | '.join(str(c) for c in r) + ' |'
                                                                          for r in rows]


def levers_table(p=None):
    p = p or _js('levers.json')
    rows = LV.lever_table(p)
    L = ['# Extended Data Table 1. The nine levers and their levels, with values and sources (generated by '
         'tools/pathways_methods.py; do not edit; main-paper Table 1 is LEVERS_TABLE_MAIN.md)', '',
         TABLE1_HEADER, '']
    L += table(['Lever', 'Strategy (PAS 2080)', 'Sub-rule', 'Rule (Reference; Ambitious; TL)', 'Anchor (Ambitious)',
                'Native parameter', 'Moderate (Level 2)', 'Ambitious (Level 3)', 'TL (Level 4)', 'Band targeted'],
               [[r['item'], r['strategy'], r['subrule'], r['rule'], r['anchor'], r['parameter'], r['moderate'],
                 r['ambitious'], r['tl'], r['band']] for r in rows])
    L += ['', 'Sources: ' + '; '.join(f'{k}: {v}' for k, v in LV.SOURCES.items()), '']
    return L


def _r(df, run, col, scen='REF'):
    return float(df[(df['scenario'] == scen) & (df['run'] == run)][col].iloc[0])


