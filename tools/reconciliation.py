"""Reconciliation of the time-resolved accounting with whole life at construction
(reference path S3-10, median demographics), written to outputs/reconciliation.json
and outputs/reconciliation.md.

At 2025 factors (DECARB_MODE 'none', A4-A5 held) the identity is exact:
    whole life at construction (baseline-pb-v2 frozen anchor)
        = upfront (A1-A5 + soil) + B events within 2026-2050
          + committed B (after 2050) + committed C1-C4.
With decarbonisation (adopted: item A1-A3 paths, A4-A5 'resch'):
    whole life at construction, A4-A5 held (baseline-pb-v2 adopted)
        - A4-A5 decarbonisation of construction
        - decarbonisation of the in-window B events
        = upfront + B within 2026-2050 + committed B (upper, 2025 factors) + committed C1-C4,
the lower committed bound holding the 2050 factors after 2050. Every term is computed
by Boss.main(); the identities are asserted.

    python tools/reconciliation.py
"""
import contextlib
import importlib
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
OUT = os.path.join(ROOT, 'outputs')
TOL = 1e-9                                         # relative


def run(**settings):
    import Boss
    M = importlib.reload(Boss)
    M.SHOW_PLOTS = False
    M.SAVE_FIGURES = False
    for k, v in settings.items():
        assert hasattr(M, k), k
        setattr(M, k, v)
    with contextlib.redirect_stdout(io.StringIO()):
        return M.main()


def split(B):
    c = B['COMMITTED']
    return dict(upfront_kt=float(B['_upfront'] + B['_soil'] / 1e6), b_inwindow_kt=float(c['B_inwindow_kt']),
                b_committed_upper_kt=float(c['B_upper_kt']), b_committed_lower_kt=float(c['B_lower_kt']),
                c_committed_kt=float(c['C_kt']), within_window_kt=float(B['tot_carbon_median']))


def close(a, b):
    return abs(a - b) <= TOL * abs(b)


def main():
    wl, tr = dict(ACCOUNTING='whole_life_at_construction'), dict(ACCOUNTING='time_resolved')
    frozen = dict(DECARB_MODE='none', DECARB_A45='held')
    adopted = dict(DECARB_MODE='horup_item', DECARB_A45='resch')
    v2_frozen = float(run(**wl, **frozen)['tot_carbon_median'])
    v2_adopted = float(run(**wl, DECARB_MODE='horup_item', DECARB_A45='held')['tot_carbon_median'])
    wl_adopted = float(run(**wl, **adopted)['tot_carbon_median'])
    s0, s1 = split(run(**tr, **frozen)), split(run(**tr, **adopted))

    sum0 = s0['upfront_kt'] + s0['b_inwindow_kt'] + s0['b_committed_upper_kt'] + s0['c_committed_kt']
    a45 = v2_adopted - wl_adopted                  # A4-A5 decarbonisation of construction
    b_dec = s0['b_inwindow_kt'] - s1['b_inwindow_kt']   # decarbonisation of in-window events
    sum1u = s1['upfront_kt'] + s1['b_inwindow_kt'] + s1['b_committed_upper_kt'] + s1['c_committed_kt']
    sum1l = s1['upfront_kt'] + s1['b_inwindow_kt'] + s1['b_committed_lower_kt'] + s1['c_committed_kt']
    checks = {
        '2025 factors: split sums to the v2 frozen whole-life total': close(sum0, v2_frozen),
        '2025 factors: committed B upper = lower': close(s0['b_committed_upper_kt'], s0['b_committed_lower_kt']),
        'decarbonised: committed C1-C4 unchanged (held at 2025)': close(s1['c_committed_kt'], s0['c_committed_kt']),
        'decarbonised: committed B upper (2025 factors) unchanged': close(s1['b_committed_upper_kt'],
                                                                         s0['b_committed_upper_kt']),
        'decarbonised: v2 adopted - A4-A5 - in-window B decarbonisation = split (upper)':
            close(v2_adopted - a45 - b_dec, sum1u),
    }
    out = dict(scenario='S3-10', v2_frozen_whole_life_kt=v2_frozen, v2_adopted_whole_life_kt=v2_adopted,
               whole_life_adopted_a45_resch_kt=wl_adopted, frozen_2025_factors=s0, adopted=s1,
               a45_construction_decarbonisation_kt=a45, b_inwindow_decarbonisation_kt=b_dec,
               sum_2025_factors_kt=sum0, sum_adopted_upper_kt=sum1u, sum_adopted_lower_kt=sum1l, checks=checks)
    with open(os.path.join(OUT, 'reconciliation.json'), 'w') as f:
        json.dump(out, f, indent=2)
    L = ['# Reconciliation: time-resolved vs whole life at construction (generated by tools/reconciliation.py)', '',
         'Reference path (S3-10), median demographics, kt CO2e. Upfront = A1-A5 of 2026-2050 construction + soil.',
         '', '| term | 2025 factors (none, A4-A5 held) | decarbonised (adopted) |', '|---|---|---|',
         f"| upfront, within 2026-2050 | {s0['upfront_kt']:,.1f} | {s1['upfront_kt']:,.1f} |",
         f"| B2/B4 events within 2026-2050 | {s0['b_inwindow_kt']:,.1f} | {s1['b_inwindow_kt']:,.1f} |",
         f"| **within 2026-2050 (reported total)** | **{s0['within_window_kt']:,.1f}** | "
         f"**{s1['within_window_kt']:,.1f}** |",
         f"| committed B after 2050 (upper: 2025 factors) | {s0['b_committed_upper_kt']:,.1f} | "
         f"{s1['b_committed_upper_kt']:,.1f} |",
         f"| committed B after 2050 (lower: 2050 factors held) | {s0['b_committed_lower_kt']:,.1f} | "
         f"{s1['b_committed_lower_kt']:,.1f} |",
         f"| committed C1-C4 (2025 factors) | {s0['c_committed_kt']:,.1f} | {s1['c_committed_kt']:,.1f} |",
         f"| sum, committed upper | {sum0:,.1f} | {sum1u:,.1f} |",
         f"| sum, committed lower | {sum0:,.1f} | {sum1l:,.1f} |",
         f"| baseline-pb-v2 whole life at construction (A4-A5 held) | {v2_frozen:,.1f} | {v2_adopted:,.1f} |",
         f"| less A4-A5 decarbonisation of construction (Resch et al. 2021) | - | {-a45:,.1f} |",
         f"| less decarbonisation of in-window B events | - | {-b_dec:,.1f} |",
         f"| = sum, committed upper | {v2_frozen:,.1f} | {v2_adopted - a45 - b_dec:,.1f} |", '',
         '| identity | holds (relative tolerance 1e-9) |', '|---|---|']
    L += [f'| {k} | {"yes" if v else "NO"} |' for k, v in checks.items()]
    with open(os.path.join(OUT, 'reconciliation.md'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('\n'.join(L))
    if not all(checks.values()):
        raise SystemExit('Reconciliation identity failed: ' + ', '.join(k for k, v in checks.items() if not v))


if __name__ == '__main__':
    main()
