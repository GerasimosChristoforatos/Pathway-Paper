"""docs/RENAMING.md section 12 (MODEL v3.3.0): the PAS 2080 restructure, old -> new map of the levers, TL components,
pathway runs, Shapley games, MC run keys and files. Generated from naming.py (LEVER_V3_2, LEVER_NAMES_V3_2,
PATHWAY_LEVERS_V3_2, STRATEGIES, STRATEGY_LEVERS) so that the documented map is the one the code uses; written between
its own markers after section 11 (tools/design_docs_v3.py keeps section 11).

    python tools/renaming_v3_3.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import naming as N  # noqa: E402

DOCS = os.path.join(ROOT, 'docs')
BEGIN = '<!-- MODEL v3.3.0 section: generated by tools/renaming_v3_3.py -->'
END = '<!-- end of MODEL v3.3.0 section -->'


def section():
    L = [BEGIN, '', '## 12. MODEL v3.3.0: PAS 2080 strategies (Avoid - Switch - Improve)', '',
         'The nine levers are regrouped by the carbon reduction hierarchy of ' + N.PAS2080 + '. Lever settings '
         '(Moderate / Ambitious / TL values, sub-rules, anchors) are unchanged; only grouping, numbering, names and '
         'order change. TLn is Level 4 of Ln and follows the new numbering (same TL values). Every deterministic total '
         'is unchanged under this map (tests/test_model_v3_3.py).', '',
         '### Levers and TL components', '',
         '| MODEL v3.0-v3.2 | MODEL v3.3.0 | strategy | TL (v3.0-v3.2 -> v3.3.0) |', '|---|---|---|---|']
    for old in sorted(N.LEVER_V3_2, key=lambda k: N.LEVER_V3_2[k]):
        new = N.LEVER_V3_2[old]
        st = N.LEVER_STRATEGY[new]
        L.append(f"| {old} {N.LEVER_NAMES_V3_2[old]} | {new} {N.LEVERS[new]} | {st} {N.STRATEGIES[st]} | "
                 f"T{old} -> T{new} {N.TL['T' + new]} |")
    L += ['', '### Pathways, strategies and runs', '',
          '| MODEL v3.0-v3.2 | MODEL v3.3.0 |', '|---|---|']
    for P, ls in N.PATHWAY_LEVERS_V3_2.items():
        L.append(f"| {P} {N.PATHWAYS[P]} ({', '.join(ls)}) | removed; its levers are now "
                 f"{', '.join(N.LEVER_V3_2[x] for x in ls)} (strategies "
                 f"{', '.join(sorted({N.LEVER_STRATEGY[N.LEVER_V3_2[x]] for x in ls}))}) |")
    for St, ls in N.STRATEGY_LEVERS.items():
        L.append(f"| (new) | {St} {N.STRATEGIES[St]}: {', '.join(ls)} (runs `{St}-moderate`, `{St}-ambitious`) |")
    L += [f"| P5 Combined, run `P5-moderate` / `P5-ambitious` | {N.PATHWAY_RUNS['pathway-moderate']} / "
          f"{N.PATHWAY_RUNS['pathway-ambitious']}, run `pathway-moderate` / `pathway-ambitious` |",
          f"| `P5-<setting>-by2030` / `-by2045` | `pathway-<setting>-by2030` / `-by2045` |",
          f"| TL Theoretical limit | {N.TL['TL']} (same run id `TL`) |",
          '| Shapley games `pathways_moderate` / `pathways_ambitious` (P1-P4) | `strategies_moderate` / '
          '`strategies_ambitious` (S1-S3) |',
          '| Shapley game `tl_from_p5_moderate` | `tl_from_moderate_pathway` |',
          '| Shapley games `levers_moderate` / `levers_ambitious` / `levers_tl` | unchanged names; players renumbered |',
          '| pathway MC run keys `P5` / `P5A` (columns `P5_*`, `P5A_*`) | `pathway_moderate` / `pathway_ambitious` |',
          '| data columns `released_tl3` / `released_tl4`, `reoccupied_tl3` / `reoccupied_tl4`, `R3` / `R4` | '
          '`released_tl1` / `released_tl2`, `reoccupied_tl1` / `reoccupied_tl2`, `R1` / `R2` (household-size and '
          'vacancy releases) |',
          '| `sensitivity/p5_carbon.csv`, figure D41_p5_sensitivity | `sensitivity/pathway_carbon.csv`, '
          'D41_pathway_sensitivity |',
          '| waterfall Reference -> P1 ... P4 (= P5) -> TL1 ... TL9 | (a) Reference -> L1 ... L9 (= Pathway), (b) '
          'Pathway -> TL1 ... TL9 (= TL), PAS 2080 order |', '',
          '### Replacement variants', '',
          f"| (new) | `VHIGH` {N.SCENARIOS['VHIGH']}: {N.SCENARIO_DEFINITIONS['VHIGH']} |", '', END]
    return L


def main():
    path = os.path.join(DOCS, 'RENAMING.md')
    text = open(path, encoding='utf-8').read()
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip('\n') + '\n'
    sec = section()
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text.rstrip('\n') + '\n\n' + '\n'.join(sec) + '\n')
    print(f'renaming_v3_3: docs/RENAMING.md section 12 ({len(sec)} lines)')


if __name__ == '__main__':
    main()
