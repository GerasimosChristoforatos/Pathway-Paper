"""Generate outputs/reports/RESULTS.md from outputs/data/metrics.json, the comparison of the Reference with
its replacement variants (outputs/data/baseline/scenarios.json) and the emissions committed after 2050 of the
planetary-boundary layer (AESA; outputs/data/aesa/results.json). Every headline number in the docs must come
from this file.

    python tools/results.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import layout  # noqa: E402
import naming as N  # noqa: E402
from metrics import FIELDS, METRICS, PB_FIELDS, get  # noqa: E402

SCEN_NAME = N.SCENARIOS                          # REF, LOW, HIGH and the sensitivity variants

README_START = '<!-- results:start (generated by tools/results.py from outputs/data/metrics.json; do not edit) -->'
README_END = '<!-- results:end -->'


def late_window_and_overlap(m):
    """(MODEL v4.10.1) The cumulative LoE over 2028-2050 and the single-lever overlap (metrics.json pathways)."""
    p = m.get('pathways') or {}
    lw, ov = p.get('loe_2028_2050'), p.get('single_lever_overlap')
    if not lw or not ov:
        return []
    names = {'reference': 'Reference', 'moderate': 'Moderate Pathway', 'ambitious': 'Ambitious Pathway',
             'tl': 'Theoretical Limit'}
    L = ['', f"## Cumulative level of exceedance over {lw['years']} (after the observed building years 2026-2027)", '',
         f"Sum of carbon over the sum of the budgets, {lw['years']} (pathways/annual.csv, scenario REF): AR budget "
         f"{lw['B_AR_kt']:,.0f} kt, AtP budget {lw['B_AtP_kt']:,.0f} kt.", '',
         '| run | carbon (kt) | LoE AR | LoE AtP |', '|---|---|---|---|']
    L += [f"| {nm} | {lw[k]['carbon_kt']:,.0f} | {lw[k]['LoE_AR']:.3f} | {lw[k]['LoE_AtP']:.3f} |"
          for k, nm in names.items() if k in lw]
    L += ['', '## Single-lever reductions against the combined reduction (2026-2050)', '',
          'The sum of the ten levers alone (Reference - Ln run) against the reduction of all ten together (Reference - '
          'Pathway or TL; pathways/runs.csv); overlap = 1 - combined / sum: the levers act on the same floor area and '
          'the same carbon per m2, so their effects are not additive.', '',
          '| level | sum of single-lever reductions (kt) | combined reduction (kt) | overlap |', '|---|---|---|---|']
    L += [f"| {lv.capitalize() if lv != 'tl' else 'TL'} | {v['sum_single_lever_reductions_kt']:,.0f} | "
          f"{v['combined_reduction_kt']:,.0f} | {v['overlap_pct']:.1f}% |" for lv, v in ov.items()]
    return L


def committed_by_run():
    """Committed after 2050 by run (MODEL v4.8.0): the deterministic range, its C1-C4 part and the share of committed
    C1-C4 in the carbon-bearing classes (held at 2025), and the Monte Carlo 90% interval of the lower bound
    (pathways/runs.csv, pathways/montecarlo_summary.csv)."""
    import pandas as pd
    rp, sp = layout.data('pathways/runs.csv'), layout.data('pathways/montecarlo_summary.csv')
    if not (os.path.exists(rp) and os.path.exists(sp)):
        return []
    r = pd.read_csv(rp)
    r = r[r['scenario'] == 'REF'].set_index('run')
    s = pd.read_csv(sp)
    L = ['', '## Committed after 2050 by run (kt CO2e)', '',
         'Lower bound: B2/B4 events after 2050 at the 2050 factors held; C1-C4 with the carbon-bearing classes (timber, '
         'plasterboard, plastics, paint, SIP) held at 2025 and the energy part at the 2050 generic construction-stage '
         'factor. Upper bound: 2025 factors. Monte Carlo: the 90% interval of the lower bound over the draws.', '',
         '| run | committed (lower-upper) | C1-C4 (lower-upper) | carbon-bearing share of C1-C4 | Monte Carlo 90% '
         'interval, lower bound |', '|---|---|---|---|---|']
    for run, mc in (('REF', 'REF'), ('pathway-moderate', 'pathway_moderate'),
                    ('pathway-ambitious', 'pathway_ambitious'), ('TL', 'TL')):
        x = r.loc[run]
        q = s[(s['run'] == mc) & (s['quantity'] == 'committed_lower_kt')]
        iv = f"{q['p5'].iloc[0]:,.0f}-{q['p95'].iloc[0]:,.0f}" if len(q) else '-'
        L.append(f"| {N.run_label(run)} | {x['committed_lower_kt']:,.0f}-{x['committed_upper_kt']:,.0f} | "
                 f"{x['committed_c1c4_lower_kt']:,.0f}-{x['committed_c1c4_upper_kt']:,.0f} | "
                 f"{100 * x['committed_c1c4_held_share']:.1f}% | {iv} |")
    return L


def readme_block(m):
    """The headline results of README.md, every number from metrics.json (the full profile only)."""
    p, mc, a = m['pathways'], m.get('mc', {}), m.get('aesa', {})
    pr = m['projection']
    L = [README_START, '',
         f"Reference 2026–2050: {pr['floor_area_Mm2']:.1f} Mm² of new residential floor area and "
         f"{pr['carbon_kt']:,.0f} kt CO₂e of embodied carbon (Monte Carlo 90% interval {mc['carbon_p5']:,.0f}–"
         f"{mc['carbon_p95']:,.0f} kt); committed after 2050 {p['committed_lower_kt']:,.0f} kt (lower bound; Monte "
         f"Carlo 90% interval {p['committed_lower_kt_mc_p5']:,.0f}–{p['committed_lower_kt_mc_p95']:,.0f} kt).", '',
         '| run | carbon 2026–2050 (kt CO₂e) | cumulative LoE of AR | cumulative LoE of AtP | P(LoE of AR ≤ 1), Monte Carlo |',
         '|---|---|---|---|---|']
    names = {'reference': 'Reference', 'moderate': 'Moderate Pathway', 'ambitious': 'Ambitious Pathway',
             'tl': 'Theoretical Limit', 'tl_tl1_age_standardised': 'Theoretical Limit, L1 at TL age-standardised (sensitivity)'}
    for k, nm in names.items():
        if k in p:
            r = p[k]
            pp = f"{100 * r['P_LoE_AR_at_most_1']:.1f}%" if 'P_LoE_AR_at_most_1' in r else 'n/a'
            L.append(f"| {nm} | {r['carbon_kt']:,.0f} | {r['LoE_AR']:.2f} | {r['LoE_AtP']:.1f} | {pp} |")
    L += ['', f"The Theoretical Limit stays within the AR budget in half of the draws when the 2050 population is "
              f"{p['tl_threshold_P_NZ_2050'] / 1e6:.2f} million. LoE > 1: the budget is exceeded "
              f"(AR = acquired rights, AtP = ability to pay; {a.get('source_pair_label', '')}).", '', README_END]
    return L


def update_readme(m):
    """Replace the block between README_START and README_END in README.md (full profile only)."""
    if m.get('run_mode') != 'full':
        return False
    path = os.path.join(ROOT, 'README.md')
    s = open(path, encoding='utf-8').read()
    i, j = s.find(README_START), s.find(README_END)
    if i < 0 or j < 0:
        raise SystemExit('results: README.md has no results markers.')
    s = s[:i] + '\n'.join(readme_block(m)) + s[j + len(README_END):]
    with open(path, 'w', encoding='utf-8') as f:
        f.write(s)
    return True


def main():
    with open(METRICS) as f:
        m = json.load(f)
    L = ['# Results (generated by tools/results.py from outputs/data/metrics.json; do not edit by hand)', '']
    if m.get('run_mode', 'full') != 'full':
        L += ['> **' + m['run_mode'] + '** (run_all.py --profile light: fewer Monte Carlo draws, '
              'no Sobol indices).', '']
    L += [
         'Reference: net replacement fading from the 2018-2023 rate to the long-run rate (half-life 10 yr); '
         '2026-2050; median demographics unless marked MC (joint uncertainty within the Reference). Carbon factors: '
         + {'none': '2025 case-study values held (frozen technology).',
            'horup_item': 'A1-A3 of case-study items decarbonised 2026-2050 (Horup et al. 2025; item-level mapping, '
                          'data/material_item_map.csv); A4-A5 e^(-0.01 (t - 2025)) (Resch et al. 2021); C1-C4, held '
                          'items and soil carbon loss at 2025.'}[(m.get('aesa') or {}).get('decarb_mode', 'none')]
         + (' Accounting: time-resolved (materials and construction (A1-A5) and soil carbon loss in the construction '
            'year; maintenance (B2, B4) in the year it occurs, 2026-2050; later B2/B4 and end of life (C1-C4) are '
            'committed after 2050, below).'
            if (m.get('aesa') or {}).get('accounting') == 'time_resolved' else ''), '',
         '| metric | value |', '|---|---|']
    for key, label, fmt in FIELDS:
        v = get(m, key)
        L.append(f"| {label} | {fmt.format(v) if v is not None else 'n/a'} |")
    sp = layout.data('baseline/scenarios.json')
    if os.path.exists(sp):
        with open(sp) as f:
            sc = json.load(f)['scenarios']
        L += ['', '## The Reference and its replacement variants (deterministic)', '',
              '| variant | floor area 2026-2050 (Mm2) | carbon 2026-2050 (kt) | of which soil carbon loss (kt) | '
              'carbon excl. soil carbon loss (kt) | materials and construction (A1-A5) and soil carbon loss (kt) |',
              '|---|---|---|---|---|---|']
        for r in (x for x in sc.values() if 'soil_carbon_loss_kt' in x):
            L.append(f"| {r['label']} | {r['floor_area_Mm2']:.2f} | {r['carbon_kt']:,.0f} | "
                     f"{r['soil_carbon_loss_kt']:,.0f} | {r['carbon_kt'] - r['soil_carbon_loss_kt']:,.0f} | "
                     f"{r['upfront_kt']:,.0f} |")
    if m.get('aesa'):
        pb = m['aesa']
        L += ['', f"## Planetary-boundary layer (AESA): climate change, {pb['source_pair_label']}", '',
              'Acquired rights (AR, Horup et al. 2025 Eq. 1) and ability to pay (AtP, Hjalsted et al. 2021 Eqs. 5-6) '
              'are a range and are never averaged. LoE = embodied carbon / boundary (> 1: exceeded). Methods: '
              'outputs/reports/METHODS_DRAFT.md, part 2 (planetary-boundary layer (AESA)).', '',
              '| metric | value |', '|---|---|']
        for key, label, fmt in PB_FIELDS:
            v = get(m, key)
            L.append(f"| {label} | {fmt.format(v) if v is not None else 'n/a'} |")
        L += ['', '| variant (deterministic) | cumulative LoE AR | cumulative LoE AtP |', '|---|---|---|']
        for k, v in pb['cum_LoE_by_scenario'].items():
            L.append(f"| {SCEN_NAME.get(k, k)} | {v['AR']:.2f} | {v['AtP']:.1f} |")
        L += ['', 'Monte Carlo (the Reference only; replacement uncertainty: the deterministic variants above, ED7 and '
              'the one-at-a-time rows):', '',
              '| run (Monte Carlo) | cumulative LoE AR p5 / p50 / p95 | cumulative LoE AtP p5 / p50 / p95 |',
              '|---|---|---|']
        for k, v in pb['cum_LoE_mc'].items():
            L.append(f"| {SCEN_NAME.get(k, k)} | {v['LoE_AR_p5']:.2f} / {v['LoE_AR_p50']:.2f} / {v['LoE_AR_p95']:.2f} | "
                     f"{v['LoE_AtP_p5']:.1f} / {v['LoE_AtP_p50']:.1f} / {v['LoE_AtP_p95']:.1f} |")
    pp = layout.data('aesa/results.json')
    if os.path.exists(pp):
        with open(pp) as f:
            cm = json.load(f).get('committed') or {}
        if cm:
            L += ['', '## Maintenance 2026-2050 and committed after 2050 (deterministic, kt CO2e)', '',
                  'Committed after 2050: later maintenance events (B2, B4; lower bound: 2050 factors held; upper '
                  'bound: 2025 factors) and all C1-C4 of the 2026-2050 cohorts (C1-C4 by material chemistry (Building_factors.C14_HELD_CLASSES): the carbon-bearing classes (timber, plasterboard, plastics, paint, SIP), whose end of life is the release of their own carbon at disposal, held at 2025 in both bounds; the energy part of the other classes (demolition, processing, transport) at 2025 factors in the upper bound and at the generic construction-stage factor e^(-0.01 (t - 2025)) (Resch et al. 2021) of 2050, held after it, in the lower bound); also in years of the '
                  '2050 AR boundary. Reconciliation with whole life at construction: outputs/reports/reconciliation.md.',
                  '',
                  '| variant | maintenance (B2, B4) 2026-2050 | share of carbon 2026-2050 | committed B2/B4 | '
                  'committed C1-C4 | committed total | years of the 2050 AR boundary |', '|---|---|---|---|---|---|---|']
            for k in ('LOW', 'REF', 'HIGH', 'VHIGH'):
                if k in cm:
                    c = cm[k]
                    L.append(f"| {SCEN_NAME[k]} | {c['maintenance_kt_sum_of_annual']:,.0f} | "
                             f"{100 * c['maintenance_share']:.1f}% | "
                             f"{c['B_lower_kt']:,.0f}-{c['B_upper_kt']:,.0f} | {c['C_lower_kt']:,.0f}-{c['C_upper_kt']:,.0f} | "
                             f"{c['lower_kt']:,.0f}-{c['upper_kt']:,.0f} | {c['years_of_B_AR_2050_lower']:.1f}-"
                             f"{c['years_of_B_AR_2050_upper']:.1f} |")
    L += committed_by_run()
    L += late_window_and_overlap(m)
    with open(layout.writing(layout.report('RESULTS.md')), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(f'outputs/reports/RESULTS.md: {len(L)} lines' + ('; README.md results block updated' if update_readme(m) else ''))


if __name__ == '__main__':
    main()
